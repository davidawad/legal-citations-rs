//! Court parentheticals to jurisdictions (lcr-k5o).
//!
//! A case citation's rule says which reporter it is; the court parenthetical
//! says which court decided it. `100 N.E.2d 1 (Ohio 2010)` is a case of the
//! Ohio Supreme Court and `2010 WL 123456 (9th Cir. 2010)` one of the Ninth
//! Circuit, whatever the rule's own jurisdiction.
//!
//! Jurisdiction ids are hierarchical down to the court, so a prefix still
//! selects the whole level (`us.fed.dist`, `us.tx`):
//!
//! | Court | Id |
//! | --- | --- |
//! | Supreme Court | `us.scotus` |
//! | courts of appeals | `us.fed.app.ca1` .. `us.fed.app.ca11`, `us.fed.app.cadc`, `us.fed.app.cafc` |
//! | district courts | `us.fed.dist.<state><district>`: `us.fed.dist.txed` (E.D. Tex.), `us.fed.dist.nysd`, `us.fed.dist.mad` (D. Mass.) |
//! | bankruptcy courts, B.A.P.s | `us.fed.bankr.<state><district>`, `us.fed.bankr.bap.ca9` |
//! | old circuit courts | `us.fed.cc.<state><district>` |
//! | other federal courts | `us.fed.cit`, `us.fed.ctcl`, `us.fed.ccpa`, `us.fed.jpml`, `us.fed.military.caaf`, ... |
//! | state courts | `us.<st>.sup` (court of last resort), `us.<st>.app` (intermediate appellate), `us.<st>.trial` |
//!
//! District codes are the state's postal code plus `nd`, `sd`, `ed`, `wd`,
//! `md`, `cd` or `d` (PACER's court ids). A court string that only starts
//! with a state abbreviation (`Ohio Ct. Com. Pl.`, not in the table) gets
//! the state (`us.oh`), not its supreme court. Foreign courts follow the
//! same shape, `foreign.<iso2>.<court>` (`foreign.il.sup`), from their
//! rules. The table is data, `courts/courts.json`, generated by
//! `cargo run -p xtask-rules` from the Indigo Book inventory
//! (`corpus/formats/indigo.jsonl`, CC0): state abbreviations from R23.3,
//! state court names from T3, federal courts from T1.
//!
//! Matching ignores whitespace and curly apostrophes (`S.D. N.Y.` is
//! `S.D.N.Y.`, `Ct. Int’l Trade` is `Ct. Int'l Trade`). The longest table
//! entry that starts the court string wins, ending on a token boundary or a
//! period (`Ohio Ct. Com. Pl.` falls back to `Ohio`, `C.C.S.D.N.Y.` to
//! `C.C.`); when the whole string does not resolve, its comma-separated
//! parts are tried from the last (`Jackson, Circuit Justice, 2d Cir.`).

use crate::citation::{Citation, Details};
use crate::rule::Kind;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::sync::OnceLock;

/// One court abbreviation as it appears in a parenthetical.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
pub struct Court {
    /// Abbreviation as Indigo prints it (`Ohio Ct. App.`, `S.D.N.Y.`).
    pub court: String,
    /// Court-level jurisdiction (`us.oh.app`, `us.fed.dist.nysd`).
    pub jurisdiction: String,
    /// Indigo Book section the entry comes from.
    pub source: String,
    /// Jurisdiction when the court string goes on past this entry
    /// (`Ohio Ct. Com. Pl.` matches `Ohio`, whose own id is `us.oh.sup`, and
    /// is `us.oh`). `None`: the entry's own.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub partial: Option<String>,
}

impl Court {
    /// The jurisdiction for a court string this entry matched: `partial`
    /// when the string goes on past the entry, else the entry's own.
    pub fn jurisdiction_for(&self, whole: bool) -> &str {
        match (&self.partial, whole) {
            (Some(p), false) => p,
            _ => &self.jurisdiction,
        }
    }
}

#[derive(Deserialize)]
struct CourtFile {
    courts: Vec<Court>,
}

/// Courts indexed by matching key.
#[derive(Clone, Debug, Default)]
pub struct CourtTable {
    courts: Vec<Court>,
    by_key: BTreeMap<String, usize>,
}

/// Matching key: no whitespace, curly apostrophes straightened.
pub fn key(s: &str) -> String {
    s.chars()
        .filter(|c| !c.is_whitespace())
        .map(|c| if c == '\u{2019}' { '\'' } else { c })
        .collect()
}

impl CourtTable {
    /// A table over `courts`; on a duplicate key the first entry wins.
    pub fn new(courts: Vec<Court>) -> CourtTable {
        let mut by_key = BTreeMap::new();
        for (i, c) in courts.iter().enumerate() {
            by_key.entry(key(&c.court)).or_insert(i);
        }
        CourtTable { courts, by_key }
    }

    /// Parse a `courts.json` file (`{"courts": [...]}`).
    pub fn from_json(json: &str) -> Result<CourtTable, String> {
        let file: CourtFile = serde_json::from_str(json).map_err(|e| e.to_string())?;
        Ok(CourtTable::new(file.courts))
    }

    /// Every entry, in file order.
    pub fn courts(&self) -> &[Court] {
        &self.courts
    }

    /// The court a parenthetical's court string names, if the table knows it.
    pub fn lookup(&self, court: &str) -> Option<&Court> {
        self.lookup_match(court).map(|(c, _)| c)
    }

    /// The jurisdiction a court string resolves to (see [`Court::partial`]).
    pub fn jurisdiction(&self, court: &str) -> Option<&str> {
        self.lookup_match(court)
            .map(|(c, whole)| c.jurisdiction_for(whole))
    }

    /// The matching entry and whether it covers the whole string.
    fn lookup_match(&self, court: &str) -> Option<(&Court, bool)> {
        self.lookup_one(court).or_else(|| {
            court
                .contains(',')
                .then(|| court.rsplit(',').find_map(|part| self.lookup_one(part)))
                .flatten()
        })
    }

    fn lookup_one(&self, s: &str) -> Option<(&Court, bool)> {
        let mut stripped = String::new();
        let mut bounds = Vec::new();
        for tok in s.split_whitespace() {
            stripped.push_str(&key(tok));
            bounds.push(stripped.len());
        }
        (1..=stripped.len())
            .rev()
            .filter(|end| stripped.is_char_boundary(*end))
            .find_map(|end| {
                let k = stripped.get(..end)?;
                let i = *self.by_key.get(k)?;
                (k.ends_with('.') || bounds.contains(&end)).then_some(())?;
                Some((self.courts.get(i)?, end == stripped.len()))
            })
    }
}

/// The embedded court table.
pub fn courts() -> &'static CourtTable {
    static CELL: OnceLock<CourtTable> = OnceLock::new();
    CELL.get_or_init(|| {
        CourtTable::from_json(include_str!("../courts/courts.json")).unwrap_or_default()
    })
}

/// Every court-level jurisdiction in the embedded table and each of its
/// dotted prefixes (`us.fed.dist.txed`, `us.fed.dist`, `us.fed`, `us`).
pub fn court_jurisdictions() -> &'static std::collections::BTreeSet<String> {
    static CELL: OnceLock<std::collections::BTreeSet<String>> = OnceLock::new();
    CELL.get_or_init(|| {
        let mut out = std::collections::BTreeSet::new();
        for c in courts().courts() {
            let mut prefix = String::new();
            for part in c.jurisdiction.split('.') {
                if !prefix.is_empty() {
                    prefix.push('.');
                }
                prefix.push_str(part);
                out.insert(prefix.clone());
            }
        }
        out
    })
}

/// Jurisdiction of a court string (`Ohio Ct. App.` -> `us.oh.app`,
/// `E.D. Tex.` -> `us.fed.dist.txed`).
pub fn jurisdiction_of(court: &str) -> Option<&'static str> {
    courts().jurisdiction(court)
}

/// The jurisdiction a citation resolves to: the court's, unless the rule's
/// is already the same or a narrower one inside it (a rule's `us.fed.dist`
/// stays when the court only says `us.fed`).
pub fn combine(rule: &str, court: &str) -> String {
    if rule == court || rule.starts_with(&format!("{court}.")) {
        rule.to_string()
    } else {
        court.to_string()
    }
}

/// Set each case citation's `jurisdiction` from its court parenthetical,
/// then give each resolved short form its antecedent's.
pub(crate) fn resolve(cites: &mut [Citation]) {
    for c in cites.iter_mut() {
        let court = match &c.details {
            Details::Case(d) if c.kind == Kind::Case => d.court.as_deref(),
            _ => None,
        };
        if let Some(j) = court.and_then(jurisdiction_of) {
            c.jurisdiction = combine(&c.rule_jurisdiction, j);
        }
    }
    for i in 0..cites.len() {
        let inherited = cites
            .get(i)
            .filter(|c| c.kind.is_short_form())
            .and_then(|c| c.antecedent)
            .filter(|j| *j < i)
            .and_then(|j| cites.get(j))
            .map(|a| a.jurisdiction.clone());
        if let (Some(j), Some(c)) = (inherited, cites.get_mut(i)) {
            c.jurisdiction = j;
        }
    }
}
